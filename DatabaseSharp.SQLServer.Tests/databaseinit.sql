CREATE OR ALTER PROCEDURE NoArguments_SingleValue
AS
BEGIN
	SELECT 1 AS SingleValue
END
GO

CREATE OR ALTER PROCEDURE NoArguments_MultiValues
AS
BEGIN
	SELECT 1 AS SingleValue
	UNION ALL
	SELECT 2 AS SingleValue
	UNION ALL
	SELECT 3 AS SingleValue
END
GO

CREATE OR ALTER PROCEDURE Arguments_SingleValue
	@ARGVALUE INT
AS
BEGIN
	SELECT @ARGVALUE AS SingleValue
END
GO

CREATE OR ALTER PROCEDURE Arguments_MultiValues
	@ARGVALUE INT
AS
BEGIN
	SELECT @ARGVALUE AS SingleValue
	UNION ALL
	SELECT @ARGVALUE + 1 AS SingleValue
	UNION ALL
	SELECT @ARGVALUE + 2 AS SingleValue
END
GO